function tr(texto, valores) {
    let saida = idioma === "en" && texto in TRADUCOES ? TRADUCOES[texto] : texto;
    if (valores) {
        for (const chave of Object.keys(valores)) saida = saida.split(`{${chave}}`).join(valores[chave]);
    }
    return saida;
}

// número com casa decimal: "1,4" em português, "1.4" em inglês
function numeroNoIdioma(texto) {
    return idioma === "en" ? texto : texto.replace(".", ",");
}

// o que a pessoa escolheu ganha; sem escolha, segue o navegador (só português fica em português)
function escolherIdioma(salvo, doNavegador) {
    if (salvo === "pt" || salvo === "en") return salvo;
    return /^pt/i.test(doNavegador || "") ? "pt" : "en";
}

// passa por uma tabela (lista ou objeto, com sublistas) e entrega cada nome, descrição e texto
function percorrerTextos(tabela, aoAchar) {
    if (Array.isArray(tabela)) {
        tabela.forEach((item) => percorrerTextos(item, aoAchar));
    } else if (tabela && typeof tabela === "object") {
        for (const campo of Object.keys(tabela)) {
            if (["nome", "descricao", "texto"].includes(campo) && typeof tabela[campo] === "string") aoAchar(tabela, campo);
            else percorrerTextos(tabela[campo], aoAchar);
        }
    }
}

// as tabelas ficam em português no logica.js; em inglês, os textos delas são trocados uma vez ao abrir
function traduzirTabelas() {
    const trocar = (dono, campo) => { dono[campo] = tr(dono[campo]); };
    percorrerTextos([CONQUISTAS, CORES_DA_COBRA, TEMAS_DO_TABULEIRO, EPOCAS, MUSICAS, MISSOES, ITENS_DA_LOJA, MAPAS_DAS_FASES, TEMA_ALTO_CONTRASTE, TEMA_DO_ABISMO], trocar);
    for (const nomes of [NOMES_DOS_MODOS, NOMES_DOS_POWERUPS]) {
        for (const chave of Object.keys(nomes)) trocar(nomes, chave);
    }
}

// troca os textos que já vêm escritos no index.html
function traduzirPagina() {
    const caminho = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    while (caminho.nextNode()) {
        const no = caminho.currentNode;
        if (no.parentNode.tagName === "SCRIPT") continue;
        const original = no.nodeValue.trim();
        const chave = original.replace(/\s+/g, " ");
        if (chave && chave in TRADUCOES) no.nodeValue = no.nodeValue.replace(original, () => TRADUCOES[chave]);
    }
    for (const elemento of document.body.querySelectorAll("[title], [aria-label], [placeholder]")) {
        for (const atributo of ["title", "aria-label", "placeholder"]) {
            const valor = elemento.getAttribute(atributo);
            if (valor && valor in TRADUCOES) elemento.setAttribute(atributo, TRADUCOES[valor]);
        }
    }
}

// primeira coisa do script.js: tudo que ele monta depois já sai no idioma certo
function aplicarIdioma() {
    idioma = escolherIdioma(lerDoArmazenamento("snakeIdioma"), navigator.language);
    if (idioma === "pt") return;

    document.documentElement.lang = "en";
    traduzirTabelas();
    traduzirPagina();
}

function trocarIdioma() {
    salvarNoArmazenamento("snakeIdioma", idioma === "pt" ? "en" : "pt");
    location.reload();
}
